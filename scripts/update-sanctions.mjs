#!/usr/bin/env node
/**
 * Refresh the vendored OFAC SDN digital-currency address snapshot (ETH list).
 *
 * Sage screens every payout recipient against this list DETERMINISTICALLY — no runtime network
 * call, no third-party API on the money path. The snapshot is vendored with its provenance and
 * date so the check is reproducible and reviewable; run this script to refresh it, and ship the
 * diff like any other reviewed change.
 *
 * Source: 0xB10C/ofac-sanctioned-digital-currency-addresses — machine-extracted from the U.S.
 * Treasury's canonical SDN list (the "Digital Currency Address - ETH" features), regenerated on
 * every SDN publication.
 *
 * Usage: node scripts/update-sanctions.mjs
 */

import { writeFileSync } from "node:fs";

const SOURCE =
  "https://raw.githubusercontent.com/0xB10C/ofac-sanctioned-digital-currency-addresses/lists/sanctioned_addresses_ETH.json";

const res = await fetch(SOURCE);
if (!res.ok) throw new Error(`fetch failed: ${res.status}`);
const raw = await res.json();
if (!Array.isArray(raw) || raw.length < 50) throw new Error(`implausible list (${raw?.length} entries) — refusing to write`);

const addrs = [...new Set(raw.map((a) => String(a).toLowerCase()))].sort();
for (const a of addrs) if (!/^0x[0-9a-f]{40}$/.test(a)) throw new Error(`not an EVM address: ${a}`);

const date = new Date().toISOString().slice(0, 10);
const out = `// GENERATED by scripts/update-sanctions.mjs — do not edit by hand; rerun the script to refresh.
// Source: U.S. Treasury OFAC SDN list, "Digital Currency Address - ETH" entries,
// via ${SOURCE}
// Snapshot: ${date} · ${addrs.length} addresses (lowercased, deduped, sorted).

export const OFAC_SDN_SNAPSHOT_DATE = "${date}";

export const OFAC_SDN_ETH: readonly string[] = ${JSON.stringify(addrs, null, 2)};
`;

writeFileSync(new URL("../src/lib/deputy/sanctions-data.ts", import.meta.url), out);
console.log(`wrote src/lib/deputy/sanctions-data.ts — ${addrs.length} addresses, snapshot ${date}`);
